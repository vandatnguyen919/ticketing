CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(255) NOT NULL,
    display_name VARCHAR(255) NOT NULL,
    provider VARCHAR(16) NOT NULL CHECK (provider IN ('GITHUB', 'GOOGLE')),
    provider_id VARCHAR(255) NOT NULL,
    CONSTRAINT uq_users_provider_identity UNIQUE (provider, provider_id)
);

INSERT INTO users (id, email, display_name, provider, provider_id)
SELECT
    id,
    email,
    name,
    UPPER(provider),
    'legacy-app-users:' || id::text
FROM app_users;

SELECT setval(
    pg_get_serial_sequence('users', 'id'),
    COALESCE(MAX(id), 1),
    MAX(id) IS NOT NULL
)
FROM users;
